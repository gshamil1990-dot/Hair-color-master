export type HairstyleLengthFilterKey = 'all' | 'short' | 'medium' | 'long';

const HAIRSTYLE_LENGTH_FILTER_BUTTONS: { key: HairstyleLengthFilterKey; label: string; hint: string }[] = [
  { key: 'all', label: 'Все длины', hint: '25 укладок' },
  { key: 'short', label: 'Короткие', hint: 'Пикси, боб, каре' },
  { key: 'medium', label: 'Средние', hint: 'До плеч и лопаток' },
  { key: 'long', label: 'Длинные', hint: 'Ниже лопаток' },
];

const matchesHairstyleLength = (style: HairstyleItem, lengthFilter: HairstyleLengthFilterKey): boolean => {
  if (lengthFilter === 'all') return true;
  const req = style.hairLengthRequirement.toLowerCase();
  if (lengthFilter === 'short') {
    return (
      req.includes('коротк') ||
      req.includes('пикси') ||
      req.includes('боб') ||
      req.includes('каре') ||
      req.includes('любая длина') ||
      req.includes('любую длину')
    );
  }
  if (lengthFilter === 'medium') {
    return (
      req.includes('средн') ||
      req.includes('каре') ||
      req.includes('боб') ||
      req.includes('lob') ||
      req.includes('любая длина') ||
      req.includes('любую длину')
    );
  }
  if (lengthFilter === 'long') {
    return (
      req.includes('длинн') ||
      req.includes('большой длины') ||
      req.includes('любая длина') ||
      req.includes('любую длину')
    );
  }
  return true;
};

